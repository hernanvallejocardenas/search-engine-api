"""Build the SQLite search index from the corpus.

Reads every .txt file in the corpus directory, tokenizes it the same way
the command-line search engine does, and writes the inverted index into a
SQLite database.

Schema:
    documents(id, filename, title, text, length)
        length is the document's token count; ranking divides term
        frequency by the square root of this number.
    postings(term, doc_id, positions)
        positions is a JSON array of token offsets (counted from 0) where
        the term occurs in the document. One row per (term, document).

Usage:
    python build_db.py [--corpus corpus] [--db search.db]

The database file is a build artifact. It is regenerated by this script
and is not committed to the repository.
"""

import argparse
import json
import os
import re
import sqlite3
from pathlib import Path

SCHEMA = """
CREATE TABLE documents (
    id INTEGER PRIMARY KEY,
    filename TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    text TEXT NOT NULL,
    length INTEGER NOT NULL
);
CREATE TABLE postings (
    term TEXT NOT NULL,
    doc_id INTEGER NOT NULL,
    positions TEXT NOT NULL,
    PRIMARY KEY (term, doc_id),
    FOREIGN KEY (doc_id) REFERENCES documents(id)
);
CREATE INDEX idx_postings_term ON postings(term);
"""


def tokenize(text):
    """Split text into lowercase words.

    Anything that is not a letter or a digit breaks a word, so punctuation
    and case do not matter: "Alice," and "alice" become the same token.
    """
    return re.findall(r"[a-z0-9]+", text.lower())


def extract_title(text, filename):
    """Take the title from the Gutenberg header line.

    The first line of each file reads "The Project Gutenberg eBook of
    <Title>". When that line is missing, fall back to the file name.
    """
    for line in text.splitlines()[:5]:
        prefix = "The Project Gutenberg eBook of "
        if line.startswith(prefix):
            return line[len(prefix):].strip()
    return Path(filename).stem.replace("-", " ").replace("_", " ").title()


def load_documents(corpus_dir):
    """Read every .txt file in a directory. Returns {file name: text}."""
    documents = {}
    for name in sorted(os.listdir(corpus_dir)):
        if not name.endswith(".txt"):
            continue
        path = os.path.join(corpus_dir, name)
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8", errors="replace") as handle:
            documents[name] = handle.read()
    return documents


def build_database(corpus_dir, db_path):
    """Build the SQLite index from the corpus.

    Returns (document count, unique term count). An existing database at
    db_path is replaced.
    """
    documents = load_documents(corpus_dir)
    if not documents:
        raise ValueError(f"No .txt files found in {corpus_dir}.")

    if os.path.exists(db_path):
        os.remove(db_path)

    connection = sqlite3.connect(db_path)
    try:
        connection.executescript(SCHEMA)
        term_count = 0
        for doc_id, (filename, text) in enumerate(documents.items(), start=1):
            tokens = tokenize(text)
            title = extract_title(text, filename)
            connection.execute(
                "INSERT INTO documents (id, filename, title, text, length)"
                " VALUES (?, ?, ?, ?, ?)",
                (doc_id, filename, title, text, len(tokens)),
            )
            # term -> [positions] for this document only.
            positions_by_term = {}
            for position, term in enumerate(tokens):
                positions_by_term.setdefault(term, []).append(position)
            connection.executemany(
                "INSERT INTO postings (term, doc_id, positions)"
                " VALUES (?, ?, ?)",
                [
                    (term, doc_id, json.dumps(positions))
                    for term, positions in positions_by_term.items()
                ],
            )
            term_count += len(positions_by_term)
        connection.commit()
    finally:
        connection.close()

    unique_terms = len(
        {term for text in documents.values() for term in set(tokenize(text))}
    )
    return len(documents), unique_terms


def main():
    parser = argparse.ArgumentParser(
        description="Build the SQLite search index from the corpus.")
    parser.add_argument("--corpus", default="corpus",
                        help="directory of .txt files (default: corpus)")
    parser.add_argument("--db", default="search.db",
                        help="SQLite file to write (default: search.db)")
    args = parser.parse_args()

    doc_count, unique_terms = build_database(args.corpus, args.db)
    print(f"Indexed {doc_count} documents, {unique_terms} unique terms. "
          f"Wrote {args.db}.")


if __name__ == "__main__":
    main()
